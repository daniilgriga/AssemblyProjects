.model tiny
.code
org 100h

LessGo:         jmp Main


; =================== CONSTANTS ===================
NL              equ 0dh, 0ah
; =================================================

;===============================================================================================
; Welcome text output
; Entry: none
; Exit:  none
; Destr: AX, DX                                                                              !!!
;===============================================================================================
SignatureOutput proc

                mov ah, 09h
                mov dx, offset Signature
                int 21h

                ret
                endp

;===============================================================================================
; Function to get user text
; Entry: none
; Exit:  none
; Destr: AX, DX, SI                                                                          !!!
;===============================================================================================
GetPassword     proc

                mov ah, 09h
                mov dx, offset AskPassword
                int 21h

                mov si, offset UserPassword

reading:
                mov ah, 01h
                int 21h
                cmp al, 0Dh
                je end_read

                mov [si], al
                inc si
                jmp reading

end_read:
                ;

                mov dx, offset UserPassword
                mov ah, 09h
                int 21h

                ret
                endp

;========================================== VARIABLES ==========================================
Signature       db  NL, "######################################################", NL, "#", NL
                db      "#  Wassup, hacker!",   NL
                db      "#  Can you crack me?", NL, "#", NL
                db      "######################################################", NL, NL, "$"

AskPassword     db  "Enter the password:", "$"

UserPassword    db  100  dup ("$")
;===============================================================================================


;===============================================================================================
;============================================ MAIN =============================================
;===============================================================================================

Main:
                call SignatureOutput

                call GetPassword

                mov ah, 4ch
                int 21h

;===============================================================================================
;===============================================================================================
;===============================================================================================

end             LessGo
